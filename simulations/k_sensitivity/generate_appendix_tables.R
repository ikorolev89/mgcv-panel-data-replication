for (configuration in config_order) {
  if (configuration == "n=500, T=4") add("\\pagebreak[4]")
  add(paste0("\\multicolumn{11}{l}{\\textit{Panel: ", panel_label(configuration), "}} \\\\"))
  add("\\midrule")
  for (dgp in dgp_order) {
    for (method in method_order_mse) {
      values <- character()
      for (k in k_order) {
        row <- mse[
          mse$configuration == configuration & mse$dgp == dgp &
            mse$method == method & mse$K_smooth == k,
          , drop = FALSE
        ]
        if (nrow(row) != 1L) stop("Nonunique MSE row")
        values <- c(
          values,
          sprintf("%.3f", row$rmse_times_100),
          format_edf(row),
          format_bind(row)
        )
      }
      add(paste0(
        dgp_label(dgp), " & ", method_label(method), " & ",
        paste(values, collapse = " & "), " \\\\"
      ))
    }
    if (dgp != tail(dgp_order, 1L)) add("\\addlinespace[2pt]")
  }
  if (configuration != tail(config_order, 1L)) add("\\midrule")
}

add(
  "\\end{longtable}",
  "{\\scriptsize\\noindent \\tablenote\\ RMSE entries report $100$ times the root mean squared error. EDF/ceiling reports the mean fitted effective degrees of freedom and its attainable ceiling. Bind reports, respectively, the fractions of Monte Carlo draws in which EDF is at least 90\\% and 95\\% of that ceiling. The ceiling is $K-1$ for the centered levels smooths used by FE and RE and $K$ for the first-difference linear-functional smooth.\\par}",
  "\\end{landscape}",
  ""
)

## Rejection frequencies for beta.
add(
  "\\begin{table}[H]",
  "\\centering",
  "\\footnotesize",
  "\\setlength{\\tabcolsep}{5pt}",
  "\\caption{Sensitivity of inference on $\\beta$ to the basis dimension}",
  "\\label{tab:k_sensitivity_beta}",
  "\\begin{tabular}{lrrrrrr}",
  "\\toprule",
  "& \\multicolumn{3}{c}{Size} & \\multicolumn{3}{c}{Power} \\\\",
  "\\cmidrule(lr){2-4} \\cmidrule(lr){5-7}",
  "Method & $K=10$ & $K=20$ & $K=40$ & $K=10$ & $K=20$ & $K=40$ \\\\",
  "\\midrule"
)

for (configuration in config_order) {
  add(paste0("\\multicolumn{7}{l}{\\textit{Panel: ", panel_label(configuration), "}} \\\\"))
  add("\\midrule")
  for (method in method_order_inference) {
    size <- numeric()
    power <- numeric()
    for (k in k_order) {
      size_row <- beta[
        beta$configuration == configuration & beta$method == method &
          beta$K_smooth == k & abs(beta$beta_true - 1) < 1e-10,
        , drop = FALSE
      ]
      power_row <- beta[
        beta$configuration == configuration & beta$method == method &
          beta$K_smooth == k & abs(beta$beta_true - 1.075) < 1e-10,
        , drop = FALSE
      ]
      if (nrow(size_row) != 1L || nrow(power_row) != 1L) stop("Nonunique beta row")
      size <- c(size, size_row$rejection_penalty_cluster)
      power <- c(power, power_row$rejection_penalty_cluster)
    }
    add(paste0(
      method_label(method), " & ",
      paste(sprintf("%.3f", c(size, power)), collapse = " & "), " \\\\"
    ))
  }
  if (configuration != tail(config_order, 1L)) add("\\midrule")
}

add(
  "\\bottomrule",
  "\\end{tabular}",
  "\\begin{minipage}{0.92\\textwidth}",
  "\\footnotesize \\tablenote\\ Entries report rejection frequencies based on the penalty-adjusted cluster sandwich. Size uses $\\beta=1$ and tests $H_0:\\beta=1$. Power uses $\\beta=1.075$ and tests the same null.",
  "\\end{minipage}",
  "\\end{table}",
  ""
)

