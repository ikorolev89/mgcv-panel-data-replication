for (configuration in config_order) {
  if (configuration == "n=500, T=4") add("\\pagebreak[4]")
  add(paste0("\\multicolumn{8}{l}{\\textit{Panel: ", panel_label(configuration), "}} \\\\"))
  add("\\midrule")
  for (model in c("beta", "pl", "np")) {
    for (method in method_order_inference) {
      values <- character()
      for (k in k_order) {
        if (model == "beta") {
          row <- beta[
            beta$configuration == configuration & beta$method == method &
              beta$K_smooth == k & abs(beta$beta_true - 1) < 1e-10,
            , drop = FALSE
          ]
        } else {
          row <- coverage[
            coverage$configuration == configuration & coverage$model == model &
              coverage$method == method & coverage$se_type == "penalty" &
              coverage$K_smooth == k,
            , drop = FALSE
          ]
        }
        if (nrow(row) != 1L) stop("Nonunique EDF row")
        values <- c(values, format_edf(row), format_bind(row))
      }
      model_name <- switch(model, beta = "$\\beta$", pl = "PL $g$", np = "NP $g$")
      add(paste0(
        model_name, " & ", method_label(method), " & ",
        paste(values, collapse = " & "), " \\\\"
      ))
    }
    if (model != "np") add("\\addlinespace[2pt]")
  }
  if (configuration != tail(config_order, 1L)) add("\\midrule")
}

