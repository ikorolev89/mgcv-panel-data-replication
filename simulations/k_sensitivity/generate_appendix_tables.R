      }
      add(paste0(
        toupper(model), " & ", method_label(method), " & ",
        paste(sprintf("%.3f", values), collapse = " & "), " \\\\"
      ))
    }
    if (model == "pl") add("\\addlinespace[2pt]")
  }
  if (configuration != tail(config_order, 1L)) add("\\midrule")
