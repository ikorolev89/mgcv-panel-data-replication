## Generate the LaTeX tables used in the manuscript appendix.
## Run this script from the project root.

mse_path <- "simulations/k_sensitivity/combined/mse_summary_all_K.csv"
beta_path <- "simulations/k_sensitivity/combined/beta_summary_all_K.csv"
coverage_path <- "simulations/k_sensitivity/combined/coverage_summary_all_K.csv"
output_path <- "paper/k_sensitivity_appendix.tex"

for (path in c(mse_path, beta_path, coverage_path)) {
  if (!file.exists(path)) {
    stop("Missing input file: ", path)
  }
}

mse <- read.csv(mse_path, check.names = FALSE)
beta <- read.csv(beta_path, check.names = FALSE)
coverage <- read.csv(coverage_path, check.names = FALSE)

config_order <- c("n=200, T=4", "n=200, T=8", "n=500, T=4")
k_order <- c(10, 20, 40)
method_order_mse <- c("mgcv::bam FD", "mgcv::bam FE", "mgcv::bam RE")
method_order_inference <- c("bam_fd", "bam_fe", "bam_re")
dgp_order <- c("linear", "quadratic", "sin_2pi")

method_label <- function(x) {
  switch(x,
    "mgcv::bam FD" = "\\code{bam} FD",
    "mgcv::bam FE" = "\\code{bam} FE",
    "mgcv::bam RE" = "\\code{bam} RE",
    "bam_fd" = "\\code{bam} FD",
    "bam_fe" = "\\code{bam} FE",
    "bam_re" = "\\code{bam} RE",
    stop("Unknown method: ", x)
  )
}

dgp_label <- function(x) {
  switch(x,
    "linear" = "linear",
    "quadratic" = "quadratic",
    "sin_2pi" = "$\\sin(2\\pi x)$",
    stop("Unknown DGP: ", x)
  )
}

panel_label <- function(configuration) {
  parts <- strsplit(configuration, ", ", fixed = TRUE)[[1]]
  paste0("$", parts[1], "$, $", parts[2], "$")
}

format_bind <- function(row) {
  sprintf("%.3f/%.3f", row$fraction_binding_90, row$fraction_binding_95)
}

format_edf <- function(row) {
  sprintf("%.2f/%.0f", row$mean_edf, row$mean_edf_ceiling)
}

one_row <- function(data, ...) {
  answer <- subset(data, ...)
  if (nrow(answer) != 1L) {
    stop("Expected one row but found ", nrow(answer))
  }
  answer
}

lines <- c(
  "% This file is generated by simulations/k_sensitivity/generate_appendix_tables.R.",
  "% Do not edit it by hand; edit the generator or the source summaries instead.",
  ""
)

add <- function(...) {
  lines <<- c(lines, ...)
}

